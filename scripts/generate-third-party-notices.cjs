const { createHash } = require('node:crypto')
const { parse } = require('@babel/parser')
const {
  existsSync,
  readFileSync,
  readdirSync,
  writeFileSync
} = require('node:fs')
const path = require('node:path')

const projectRoot = path.resolve(__dirname, '..')
const outputPath = path.join(projectRoot, 'THIRD_PARTY_NOTICES.md')
const lock = readJson(path.join(projectRoot, 'package-lock.json'))
const lockPackages = lock.packages

const distributedRoots = [
  '@fontsource-variable/jetbrains-mono',
  '@mdxeditor/editor',
  '@xterm/addon-fit',
  '@xterm/xterm',
  '@xyflow/react',
  'better-sqlite3',
  'class-variance-authority',
  'clsx',
  'cmdk',
  'font-list',
  'i18next',
  'lucide-react',
  'node-pty',
  'radix-ui',
  'react',
  'react-dom',
  'react-i18next',
  'sonner',
  'tailwind-merge',
  'tailwindcss',
  'tw-animate-css'
]

// Electron's runtime is distributed as a whole, while shadcn supplies CSS and
// copied component source. Their package-manager-only dependency trees are not
// part of the application, so only their own notices belong in this document.
const directNoticeRoots = ['electron', 'shadcn']

const noticeOverrides = {
  'cm6-theme-basic-light@0.2.0': 'cm6-theme-basic-light.txt',
  'format@0.2.2': 'format.txt',
  'mdast-util-highlight-mark@1.2.2': 'remark-highlight-mark.txt',
  'micromark-extension-highlight-mark@1.2.0': 'remark-highlight-mark.txt',
  'react-remove-scroll-bar@2.3.8': 'react-remove-scroll-bar.txt'
}

const supplementalLegalFiles = {
  'node-pty@1.1.0': ['deps/winpty/LICENSE']
}

main()

function main() {
  const args = process.argv.slice(2)
  if (args.some((argument) => argument !== '--check') || args.length > 1) {
    throw new Error('Usage: node scripts/generate-third-party-notices.cjs [--check]')
  }

  const notice = generateNotice()
  if (args[0] === '--check') {
    const current = existsSync(outputPath)
      ? readFileSync(outputPath, 'utf8').replaceAll('\r\n', '\n')
      : ''
    if (current !== notice) {
      process.stderr.write(
        'THIRD_PARTY_NOTICES.md is stale. Run npm run licenses:generate and review the result.\n'
      )
      process.exitCode = 1
    }
    return
  }

  writeFileSync(outputPath, notice, 'utf8')
  process.stdout.write(`Wrote ${path.relative(projectRoot, outputPath)}\n`)
}

function generateNotice() {
  if (!lockPackages || typeof lockPackages !== 'object') {
    throw new Error('package-lock.json does not contain a packages map')
  }

  validateApplicationImports()
  const selectedKeys = collectDistributedPackageKeys()
  const componentsByIdentity = new Map()
  for (const installKey of selectedKeys) {
    const component = readComponent(installKey)
    const identity = `${component.name}\0${component.version}`
    const existing = componentsByIdentity.get(identity)
    if (existing && existing.noticeText !== component.noticeText) {
      throw new Error(`Conflicting notices for ${component.name}@${component.version}`)
    }
    if (!existing) componentsByIdentity.set(identity, component)
  }

  const components = [...componentsByIdentity.values()].sort(compareComponents)
  const groupsByHash = new Map()
  for (const component of components) {
    const hash = createHash('sha256').update(component.noticeText).digest('hex')
    const group = groupsByHash.get(hash)
    if (group) {
      if (group.noticeText !== component.noticeText) {
        throw new Error(`Notice hash collision for ${component.name}@${component.version}`)
      }
      group.components.push(component)
    } else {
      groupsByHash.set(hash, { noticeText: component.noticeText, components: [component] })
    }
  }

  const groups = [...groupsByHash.values()].sort((left, right) => (
    compareComponents(left.components[0], right.components[0])
  ))
  const groupIdByComponent = new Map()
  groups.forEach((group, index) => {
    group.id = String(index + 1).padStart(3, '0')
    group.components.sort(compareComponents)
    for (const component of group.components) {
      groupIdByComponent.set(`${component.name}\0${component.version}`, group.id)
    }
  })

  const lines = [
    '<!-- Generated by scripts/generate-third-party-notices.cjs. Do not edit directly. -->',
    '',
    '# Third-party notices',
    '',
    'CLILoom includes or derives distributed application assets from the packages listed below. Exact versions come from `package-lock.json`; license and notice text comes from the installed package, with reviewed upstream overrides only when an npm package omitted that text.',
    '',
    'CLILoom itself is licensed under Apache License 2.0 as stated in `LICENSE`. This document does not replace or alter any third-party license. The relevant license text controls each component.',
    '',
    'The Electron runtime also distributes its own `LICENSE` and `LICENSES.chromium.html` files for Electron, Chromium, Node.js, and their incorporated components. Those runtime files remain part of packaged Electron applications and are not duplicated in this Markdown document.',
    '',
    `This generated inventory contains ${components.length} package versions and ${groups.length} distinct notice texts. Refresh it with \`npm run licenses:generate\`; builds verify it with \`npm run licenses:check\`.`,
    '',
    '## Component index',
    '',
    '| Package | Version | Declared license | Text |',
    '| --- | --- | --- | --- |'
  ]

  for (const component of components) {
    const groupId = groupIdByComponent.get(`${component.name}\0${component.version}`)
    const packageUrl = `https://www.npmjs.com/package/${component.name}`
    lines.push(
      `| [${escapeTableCell(component.name)}](${packageUrl}) | \`${escapeTableCell(component.version)}\` | ${escapeTableCell(component.license)} | [Notice ${groupId}](#notice-${groupId}) |`
    )
  }

  lines.push('', '## License and notice texts', '')
  for (const group of groups) {
    const declaredLicenses = [...new Set(group.components.map((component) => component.license))]
      .sort()
      .join(', ')
    lines.push(
      `### Notice ${group.id}`,
      '',
      `Applies to: ${group.components.map(formatComponent).join(', ')}`,
      '',
      `Declared license: ${declaredLicenses}`,
      '',
      `${fenceFor(group.noticeText)}text`,
      group.noticeText,
      fenceFor(group.noticeText),
      ''
    )
  }

  return `${lines.join('\n').trimEnd()}\n`
}

function collectDistributedPackageKeys() {
  const selected = new Set()
  const queue = distributedRoots.map((name) => ({
    installKey: rootInstallKey(name),
    includeDependencies: true
  }))
  queue.push(...directNoticeRoots.map((name) => ({
    installKey: rootInstallKey(name),
    includeDependencies: false
  })))

  while (queue.length > 0) {
    const current = queue.shift()
    if (selected.has(current.installKey)) continue
    selected.add(current.installKey)
    if (!current.includeDependencies) continue

    const lockEntry = lockPackages[current.installKey]
    const optionalDependencies = Object.keys(lockEntry.optionalDependencies ?? {})
    if (optionalDependencies.length > 0) {
      throw new Error(
        `${current.installKey} has optional runtime dependencies; review their packaging and notice policy`
      )
    }
    const runtimeDependencies = new Set(Object.keys(lockEntry.dependencies ?? {}))
    for (const [peerName, metadata] of Object.entries(lockEntry.peerDependenciesMeta ?? {})) {
      if (metadata.optional) runtimeDependencies.delete(peerName)
    }
    for (const peerName of Object.keys(lockEntry.peerDependencies ?? {})) {
      if (!lockEntry.peerDependenciesMeta?.[peerName]?.optional) runtimeDependencies.add(peerName)
    }
    for (const dependencyName of [...runtimeDependencies].sort()) {
      queue.push({
        installKey: resolveDependencyKey(current.installKey, dependencyName),
        includeDependencies: true
      })
    }
  }

  return [...selected].sort()
}

function validateApplicationImports() {
  const configuredRoots = new Set([...distributedRoots, ...directNoticeRoots])
  const importedPackages = new Set()
  for (const sourceDirectory of ['src/main', 'src/renderer', 'src/shared']) {
    for (const filePath of collectSourceFiles(path.join(projectRoot, sourceDirectory))) {
      const source = readFileSync(filePath, 'utf8')
      for (const specifier of findRuntimeImports(source, path.extname(filePath))) {
        const packageName = packageNameFromSpecifier(specifier)
        if (packageName) importedPackages.add(packageName)
      }
    }
  }

  const missing = [...importedPackages]
    .filter((packageName) => !configuredRoots.has(packageName))
    .sort()
  if (missing.length > 0) {
    throw new Error(
      `Add imported application packages to the third-party notice roots: ${missing.join(', ')}`
    )
  }
}

function collectSourceFiles(directoryPath) {
  const files = []
  for (const entry of readdirSync(directoryPath, { withFileTypes: true })) {
    const entryPath = path.join(directoryPath, entry.name)
    if (entry.isDirectory()) {
      files.push(...collectSourceFiles(entryPath))
    } else if (
      entry.isFile() &&
      /\.(css|ts|tsx)$/.test(entry.name) &&
      !/\.(d|test)\.tsx?$/.test(entry.name)
    ) {
      files.push(entryPath)
    }
  }
  return files
}

function findRuntimeImports(source, extension) {
  if (extension === '.css') {
    return [...source.matchAll(/@import\s+(?:url\()?\s*['"]([^'"]+)['"]/g)]
      .map((match) => match[1])
  }

  const specifiers = []
  const sourceFile = parse(source, {
    sourceType: 'module',
    plugins: ['typescript', ...(extension === '.tsx' ? ['jsx'] : [])]
  })
  const visit = (node) => {
    if (!node || typeof node !== 'object') return
    if (node.type === 'ImportDeclaration') {
      if (node.importKind !== 'type') specifiers.push(node.source.value)
    } else if (
      (node.type === 'ExportNamedDeclaration' || node.type === 'ExportAllDeclaration') &&
      node.exportKind !== 'type' &&
      node.source
    ) {
      specifiers.push(node.source.value)
    } else if (
      node.type === 'CallExpression' &&
      (node.callee.type === 'Import' ||
        (node.callee.type === 'Identifier' && node.callee.name === 'require')) &&
      node.arguments.length === 1 &&
      node.arguments[0].type === 'StringLiteral'
    ) {
      specifiers.push(node.arguments[0].value)
    } else if (node.type === 'ImportExpression' && node.source.type === 'StringLiteral') {
      specifiers.push(node.source.value)
    }
    for (const [key, value] of Object.entries(node)) {
      if (['comments', 'errors', 'extra', 'loc'].includes(key)) continue
      if (Array.isArray(value)) {
        for (const child of value) visit(child)
      } else if (value && typeof value === 'object' && typeof value.type === 'string') {
        visit(value)
      }
    }
  }
  visit(sourceFile)
  return specifiers
}

function packageNameFromSpecifier(specifier) {
  if (
    specifier.startsWith('.') ||
    specifier.startsWith('/') ||
    specifier.startsWith('@/') ||
    specifier.startsWith('node:')
  ) return ''
  const segments = specifier.split('/')
  return specifier.startsWith('@') ? segments.slice(0, 2).join('/') : segments[0]
}

function rootInstallKey(packageName) {
  const installKey = path.posix.join('node_modules', packageName)
  if (!lockPackages[installKey]) throw new Error(`Missing locked package ${packageName}`)
  return installKey
}

function resolveDependencyKey(parentKey, dependencyName) {
  let ancestor = parentKey
  while (true) {
    const candidate = path.posix.join(ancestor, 'node_modules', dependencyName)
    if (lockPackages[candidate]) return candidate
    if (!ancestor) break
    const separator = ancestor.lastIndexOf('/')
    ancestor = separator === -1 ? '' : ancestor.slice(0, separator)
  }
  throw new Error(`Cannot resolve ${dependencyName} from ${parentKey} in package-lock.json`)
}

function readComponent(installKey) {
  const lockEntry = lockPackages[installKey]
  const packageDirectory = path.join(projectRoot, ...installKey.split('/'))
  const manifestPath = path.join(packageDirectory, 'package.json')
  if (!existsSync(manifestPath)) {
    throw new Error(`Install dependencies before generating notices: missing ${manifestPath}`)
  }

  const manifest = readJson(manifestPath)
  if (manifest.version !== lockEntry.version) {
    throw new Error(
      `Installed ${manifest.name}@${manifest.version} does not match lockfile version ${lockEntry.version}`
    )
  }

  const license = readDeclaredLicense(manifest, lockEntry)
  const legalFiles = readdirSync(packageDirectory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && isLegalFilename(entry.name))
    .map((entry) => entry.name)
  legalFiles.push(...(supplementalLegalFiles[`${manifest.name}@${manifest.version}`] ?? []))
  legalFiles.sort((left, right) => left.localeCompare(right, 'en'))

  let noticeText
  if (legalFiles.length > 0) {
    noticeText = legalFiles.map((filename) => {
      const legalPath = path.join(packageDirectory, filename)
      if (!existsSync(legalPath)) {
        throw new Error(`Missing supplemental legal file for ${manifest.name}: ${filename}`)
      }
      const content = normalizeText(readFileSync(legalPath, 'utf8'))
      return legalFiles.length === 1 ? content : `--- ${filename} ---\n\n${content}`
    }).join('\n\n')
  } else {
    const overrideFilename = noticeOverrides[`${manifest.name}@${manifest.version}`]
    if (!overrideFilename) {
      throw new Error(`No license or notice text found for ${manifest.name}@${manifest.version}`)
    }
    noticeText = normalizeText(readFileSync(
      path.join(projectRoot, 'third_party', 'license-overrides', overrideFilename),
      'utf8'
    ))
  }

  const fontAttribution = readFontAttribution(packageDirectory, manifest.name)
  if (fontAttribution) noticeText = `${fontAttribution}\n\n${noticeText}`

  return {
    name: manifest.name,
    version: manifest.version,
    license,
    noticeText
  }
}

function readDeclaredLicense(manifest, lockEntry) {
  const value = manifest.license ?? lockEntry.license
  if (typeof value === 'string' && value.trim()) return value.trim()
  if (Array.isArray(manifest.licenses)) {
    const types = manifest.licenses
      .map((entry) => typeof entry === 'string' ? entry : entry?.type)
      .filter((entry) => typeof entry === 'string' && entry.trim())
    if (types.length > 0) return [...new Set(types)].join(' OR ')
  }
  throw new Error(`Missing declared license for ${manifest.name}@${manifest.version}`)
}

function readFontAttribution(packageDirectory, packageName) {
  if (!packageName.startsWith('@fontsource-variable/')) return ''
  const metadata = readJson(path.join(packageDirectory, 'metadata.json'))
  const attribution = metadata.license?.attribution
  if (typeof attribution !== 'string' || !attribution.trim()) {
    throw new Error(`Missing font attribution for ${packageName}`)
  }
  return `FONT ATTRIBUTION\n${attribution.trim()}`
}

function isLegalFilename(filename) {
  return /^(licen[cs]e|copying|notice|third[-_. ]?party|copyright|authors|credits|patents)(?:[.\-_ ]|$)/i
    .test(filename)
}

function readJson(filePath) {
  return JSON.parse(readFileSync(filePath, 'utf8'))
}

function normalizeText(value) {
  return value.replaceAll('\r\n', '\n').trim()
}

function compareComponents(left, right) {
  return left.name.localeCompare(right.name, 'en') ||
    left.version.localeCompare(right.version, 'en')
}

function formatComponent(component) {
  return `\`${component.name}@${component.version}\``
}

function escapeTableCell(value) {
  return value.replaceAll('|', '\\|')
}

function fenceFor(value) {
  const longestRun = Math.max(0, ...[...value.matchAll(/`+/g)].map((match) => match[0].length))
  return '`'.repeat(Math.max(3, longestRun + 1))
}
